// Bundles all Markdown/JSON content into src/generated/content.ts (single source for MCP, plugin and site).
// Also materialises doc-backed skill references (content/skill-doc-links.json) so skills stay self-contained.
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync, copyFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const content = join(root, "content");

function walk(dir) {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

function frontmatter(md) {
  const m = md.match(/^---\n([\s\S]*?)\n---\n?/);
  const meta = {};
  if (m) for (const line of m[1].split("\n")) {
    const i = line.indexOf(":");
    if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  return { meta, body: m ? md.slice(m[0].length) : md };
}

// 0. link check: every relative .md link in docs must resolve; rewrite to docs:// URIs for the MCP
import { existsSync } from "node:fs";
import { posix } from "node:path";
const linkRe = /\]\(((?!https?:|#|mailto:|docs:|skill:)[^)\s]+\.md)(#[^)]*)?\)/g;
function toDocUris(md, fromSlug) {
  return md.replace(linkRe, (all, href, hash) => {
    const target = posix.normalize(posix.join(posix.dirname(fromSlug), href)).replace(/\.md$/, "");
    if (!existsSync(join(content, "docs", target + ".md"))) throw new Error(`broken link in docs/${fromSlug}.md → ${href}`);
    return `](docs://voltox/${target}${hash ?? ""})`;
  });
}

// 1. materialise doc-backed references
const links = JSON.parse(readFileSync(join(content, "skill-doc-links.json"), "utf8"));
for (const [skill, files] of Object.entries(links)) {
  const dir = join(content, "skills", skill, "references");
  mkdirSync(dir, { recursive: true });
  for (const [target, src] of Object.entries(files)) writeFileSync(join(dir, target), toDocUris(readFileSync(join(content, "docs", src), "utf8"), src.replace(/\.md$/, "")));
}

// 2. docs
const docs = walk(join(content, "docs")).filter((f) => f.endsWith(".md")).map((f) => {
  const raw = readFileSync(f, "utf8");
  const { meta, body } = frontmatter(raw);
  const slug = relative(join(content, "docs"), f).replace(/\.md$/, "");
  return { slug, title: meta.title ?? slug, section: meta.section ?? "Docs", order: Number(meta.order ?? 99), summary: meta.summary ?? "", body: toDocUris(body, slug) };
});

// 3. skills
const skills = readdirSync(join(content, "skills")).map((name) => {
  const dir = join(content, "skills", name);
  const { meta, body } = frontmatter(readFileSync(join(dir, "SKILL.md"), "utf8"));
  if (meta.name !== name) throw new Error(`Skill folder ${name} != name ${meta.name}`);
  const refDir = join(dir, "references");
  let references = {};
  try {
    references = Object.fromEntries(readdirSync(refDir).filter((f) => f.endsWith(".md")).map((f) => [f, readFileSync(join(refDir, f), "utf8")]));
  } catch {}
  return { name, description: meta.description ?? "", body, references };
});

// 4. assessments + api registry
const assessments = {
  terminal: JSON.parse(readFileSync(join(content, "assessments", "terminal.json"), "utf8")),
  api: JSON.parse(readFileSync(join(content, "assessments", "api.json"), "utf8")),
};
const operations = JSON.parse(readFileSync(join(content, "api", "operations.json"), "utf8"));

const out = `// GENERATED by scripts/build-content.mjs — do not edit.\n` +
  `export const DOCS = ${JSON.stringify(docs)} as const;\n` +
  `export const SKILLS = ${JSON.stringify(skills)} as const;\n` +
  `export const ASSESSMENTS = ${JSON.stringify(assessments)} as any;\n` +
  `export const OPERATIONS = ${JSON.stringify(operations)} as any;\n` +
  `export const CONTENT_VERSION = ${JSON.stringify(new Date().toISOString().slice(0, 10))};\n`;
mkdirSync(join(root, "src", "generated"), { recursive: true });
writeFileSync(join(root, "src", "generated", "content.ts"), out);
console.log(`content: ${docs.length} docs, ${skills.length} skills, ${assessments.terminal.requirements.length + assessments.terminal.tests.length} terminal items, ${assessments.api.requirements.length + assessments.api.tests.length} api items`);
